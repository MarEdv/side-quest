// Copies the shared modules in kit/ into the games that use them (K-1..K-4, D-9). No dependencies.
// A game lists the modules it wants in its package.json ("kit": ["storage.js", ...]); each one is written to
// games/<slug>/src/kit/<name> under a "generated" header, so the game stays self-contained (rule 4).
// Usage: node tools/sync-kit.mjs          writes the copies and removes ones no longer listed
//        node tools/sync-kit.mjs --check  exits non-zero if a copy is missing, edited or left over
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT } from './build-registry.mjs';

export const NAME_RE = /^[a-z0-9][a-z0-9-]*\.js$/;

export const header = (name) =>
  `// GENERATED by "npm run kit" from kit/${name} at the repo root. Do not edit this copy: change kit/${name} and run npm run kit.\n`;

// The other kit modules a module imports ('./x.js'): a game that lists the module must list these too.
export function kitImports(source) {
  const out = new Set();
  for (const m of source.matchAll(/(?:\bfrom\s*|\bimport\s*\(?\s*)['"]\.\/([^'"]+)['"]/g)) out.add(m[1]);
  return [...out];
}

// What the copies should be. Returns { expected: Map<path relative to root, text>, extra: [paths that should not exist],
// errors: [problems with a "kit" list] }.
export function collectKit(root = ROOT) {
  const kitDir = join(root, 'kit'), gamesDir = join(root, 'games');
  const expected = new Map(), extra = [], errors = [];
  const modules = new Map();
  if (existsSync(kitDir)) {
    for (const d of readdirSync(kitDir, { withFileTypes: true })) {
      if (d.isFile() && d.name.endsWith('.js')) modules.set(d.name, readFileSync(join(kitDir, d.name), 'utf8'));
    }
  }
  for (const name of modules.keys()) if (!NAME_RE.test(name)) errors.push(`kit/${name}: module names are lower-case, e.g. storage.js`);
  for (const [name, source] of modules) {
    for (const dep of kitImports(source)) if (!modules.has(dep)) errors.push(`kit/${name} imports ./${dep}, which is not in kit/`);
  }
  if (!existsSync(gamesDir)) return { expected, extra, errors };

  for (const d of readdirSync(gamesDir, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name.startsWith('.')) continue;
    const rel = `games/${d.name}`;
    let wanted = [];
    const pkgPath = join(gamesDir, d.name, 'package.json');
    if (existsSync(pkgPath)) {
      let pkg = null;
      try { pkg = JSON.parse(readFileSync(pkgPath, 'utf8')); } catch (e) { errors.push(`${rel}/package.json: ${e.message}`); }
      const list = pkg?.kit;
      if (list !== undefined) {
        if (!Array.isArray(list) || !list.every((n) => typeof n === 'string')) errors.push(`${rel}/package.json: "kit" must be a list of module names`);
        else wanted = [...new Set(list)];
      }
    }
    for (const name of wanted) {
      if (!modules.has(name)) { errors.push(`${rel}/package.json: "kit" lists ${name}, which is not in kit/`); continue; }
      for (const dep of kitImports(modules.get(name))) {
        if (modules.has(dep) && !wanted.includes(dep)) errors.push(`${rel}/package.json: "kit" lists ${name}, which needs ${dep} too`);
      }
      expected.set(`${rel}/src/kit/${name}`, header(name) + modules.get(name));
    }
    const copyDir = join(gamesDir, d.name, 'src', 'kit');
    if (existsSync(copyDir)) {
      for (const f of readdirSync(copyDir)) if (!expected.has(`${rel}/src/kit/${f}`)) extra.push(`${rel}/src/kit/${f}`);
    }
  }
  return { expected, extra, errors };
}

// Everything that is wrong with the copies on disk (empty = in sync).
export function checkKit(root = ROOT) {
  const { expected, extra, errors } = collectKit(root);
  const problems = [...errors];
  for (const [rel, text] of expected) {
    const path = join(root, rel);
    if (!existsSync(path)) problems.push(`${rel} is missing: run npm run kit`);
    else if (readFileSync(path, 'utf8') !== text) problems.push(`${rel} differs from its kit/ module: edit kit/, then run npm run kit`);
  }
  for (const rel of extra) problems.push(`${rel} is not listed in the game's "kit": run npm run kit`);
  return problems;
}

// Writes the copies. Returns { written, removed, errors }; writes nothing when a "kit" list is wrong.
export function writeKit(root = ROOT) {
  const { expected, extra, errors } = collectKit(root);
  if (errors.length) return { written: [], removed: [], errors };
  const written = [];
  for (const [rel, text] of expected) {
    const path = join(root, rel);
    if (existsSync(path) && readFileSync(path, 'utf8') === text) continue;
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, text);
    written.push(rel);
  }
  for (const rel of extra) {
    rmSync(join(root, rel), { recursive: true });
    const dir = join(root, rel, '..');
    if (!readdirSync(dir).length) rmSync(dir, { recursive: true });
  }
  return { written, removed: extra, errors };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const problems = checkKit();
    if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
    console.log(`kit copies are up to date (${collectKit().expected.size} files)`);
  } else {
    const { written, removed, errors } = writeKit();
    if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
    for (const rel of written) console.log(`wrote ${rel}`);
    for (const rel of removed) console.log(`removed ${rel}`);
    if (!written.length && !removed.length) console.log('kit copies already up to date');
  }
}
