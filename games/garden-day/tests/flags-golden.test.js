test('defaults are unchanged', () => {
  assert.deepEqual({ ...DEFAULT_FLAGS }, DEFAULTS);
  assert.deepEqual(Object.keys(DEFAULT_FLAGS), Object.keys(DEFAULTS)); // the settings screen lists flags in this order
  assert.deepEqual(parseFlags(), DEFAULTS);
});

test('parseFlags: every query gives the same flags as before', () => {
  for (const [q, diff] of ROWS) assert.deepEqual(parseFlags(q), { ...DEFAULTS, ...diff }, q);
});

test('parseFlagValue: typed values (saved settings) give the same result as before', () => {
  for (const [key, raw, want] of VALUES) assert.equal(parseFlagValue(key, raw), want, `${key}=${String(raw)}`);
});

test('parseFlagEntries: only the valid flags a query sets', () => {
  assert.deepEqual(parseFlagEntries(''), {});
  assert.deepEqual(parseFlagEntries('wifeMode=random&bogus=1&sound=x'), { wifeMode: 'random' });
  assert.deepEqual(parseFlagEntries('sound=0&sound=1&seed=RANDOM'), { sound: true, seed: 'random' });
  assert.deepEqual(parseFlagEntries('sound=1&touch=auto'), { sound: true, touch: 'auto' }); // a default value still counts as set
});
